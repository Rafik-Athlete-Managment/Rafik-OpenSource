import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const web = resolve(root, "../frontend");
const content = JSON.parse(
  readFileSync(resolve(root, "content/starter.json"), "utf8"),
);
const quoted = (value) =>
  value === null ? "NULL" : "'" + String(value).replaceAll("'", "''") + "'";
const columns = [
  "id",
  "name",
  "name_ar",
  "equipment",
  "equipment_ar",
  "instructions",
  "instructions_ar",
  "movement",
  "kind",
  "media_ref",
  "category",
  "body_part",
  "target_muscle",
];
const ids = new Set(content.exercises.map((e) => e.id));
if (ids.size !== content.exercises.length) throw Error("Duplicate exercise ID");
for (const e of content.exercises)
  for (const column of columns.filter((c) => c !== "media_ref"))
    if (typeof e[column] !== "string" || !e[column])
      throw Error(`Missing ${column} in ${e.id}`);
for (const day of content.prescription.days)
  for (const e of day.exercises)
    if (!ids.has(e.exerciseId)) throw Error(`Unknown exercise ${e.exerciseId}`);
const prescription = quoted(JSON.stringify(content.prescription)) + "::jsonb";
const seed = `-- GENERATED by npm run content. Synthetic optional local fixtures only.
insert into public.reference_exercises(${columns.join(",")}) values ${content.exercises.map((e) => "(" + columns.map((c) => quoted(e[c])).join(",") + ")").join(",\n")};
${readFileSync(resolve(root, "prisma/fixtures/users.sql"), "utf8")}
`;
const outputs = [
  [
    resolve(root, "prisma/seed.sql"),
    seed +
      readFileSync(resolve(root, "prisma/fixtures/institutions.sql"), "utf8") +
      readFileSync(
        resolve(root, "prisma/fixtures/programming.sql"),
        "utf8",
      ).replace("__SAMPLE_PRESCRIPTION__", prescription) +
      readFileSync(
        resolve(root, "prisma/fixtures/institution-services.sql"),
        "utf8",
      ) +
      readFileSync(resolve(root, "prisma/fixtures/communication.sql"), "utf8") +
      readFileSync(resolve(root, "prisma/fixtures/platform.sql"), "utf8"),
  ],
  [
    resolve(web, "src/content/sample.json"),
    JSON.stringify(content, null, 2) + "\n",
  ],
];
outputs.push([
  resolve(web, "src/content/exercise-media.json"),
  readFileSync(resolve(root, "content/exercise-media.json"), "utf8"),
]);
const media = JSON.parse(
  readFileSync(resolve(root, "content/exercise-media.json"), "utf8"),
);
for (const item of media.items)
  for (const frame of item.frames) {
    const relative = `exercise-media/${item.id}/${frame.index}.svg`;
    outputs.push([
      resolve(web, "public", relative),
      readFileSync(resolve(root, "content", relative), "utf8"),
    ]);
  }
outputs.push([
  resolve(web, "public/exercise-media/CREDITS.txt"),
  `Exercise artwork: Bryl Lim / Workout Guide. Original glute-bridge pose: Everkinetic.\nSource commit: ${media.source.commit}. Assets unchanged by Rafik.\nAll illustration files in this directory are CC BY-SA 4.0. Application code is separate.\nSource and per-frame attribution: /v1/catalog/exercise-media on the Rafik API.\n\n` +
    readFileSync(
      resolve(root, "content/upstream/workout-guide/LICENSE-ASSETS"),
      "utf8",
    ) +
    "\n" +
    readFileSync(
      resolve(root, "content/upstream/workout-guide/ATTRIBUTION.md"),
      "utf8",
    ),
]);
const videos = readFileSync(
  resolve(root, "content/exercise-videos.json"),
  "utf8",
);
outputs.push([resolve(web, "src/content/exercise-videos.json"), videos]);
const wger = JSON.parse(
  readFileSync(
    resolve(root, "content/upstream/wger/exercise-snapshot.json"),
    "utf8",
  ),
);
const credits = Object.fromEntries(
  wger.records.map((record) => {
    const provenance = record.instructionProvenance;
    const source = provenance.source;
    const license = source?.license || record.exerciseLicense;
    return [
      record.id,
      {
        author:
          source?.licenseAuthor ||
          (provenance.mode === "rafik-authored"
            ? "Rafik"
            : record.exerciseLicenseAuthor),
        license: license.short_name || license.shortName,
        licenseUrl: license.url,
        sourceUrl: record.sourceUrl,
        adapted: record.instructionStatus !== "source",
      },
    ];
  }),
);
outputs.push([
  resolve(web, "src/content/exercise-credits.json"),
  JSON.stringify(credits, null, 2) + "\n",
]);
for (const [path, data] of outputs) {
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== data)
      throw Error(`Regenerate content: ${path}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    if (!existsSync(path) || readFileSync(path, "utf8") !== data)
      writeFileSync(path, data);
  }
}
console.log(
  process.argv.includes("--check")
    ? "Content outputs match the canonical source."
    : "Generated local seed and public content from content/starter.json.",
);
